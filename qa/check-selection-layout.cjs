const { chromium } = require('C:/Users/aa404/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')

;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
  try {
    for (const [width,height] of [[390,844],[440,956],[496,884]]) {
      const page = await browser.newPage({ viewport: { width,height }, deviceScaleFactor: 1 })
      await page.goto('http://127.0.0.1:5173/#/subpages/tarot/index?theme=' + encodeURIComponent('爱情'))
      await page.evaluate(() => localStorage.clear())
      await page.reload()
      await page.locator('.flow-intro-button').click()
      await page.waitForTimeout(600)
      if (await page.locator('.flow-select-progress').count() !== 0) throw Error('Duplicate selection progress is still visible')
      const result = await page.evaluate(() => {
        const rect = selector => { const r = document.querySelector(selector).getBoundingClientRect(); return {x:r.x,y:r.y,width:r.width,height:r.height} }
        const fan = document.querySelector('.flow-select-fan').getBoundingClientRect()
        const visibleCards = [...document.querySelectorAll('.flow-fan-card')].filter(card => {const r=card.getBoundingClientRect();return r.right>fan.left && r.left<fan.right}).length
        return {stage:rect('.flow-select-stage'),header:rect('.flow-select-header-panel'),heading:rect('.flow-select-heading'),subtitle:rect('.flow-select-subtitle'),fan:rect('.flow-select-fan'),slots:rect('.flow-select-slots'),hint:rect('.flow-select-hint'),card:rect('.flow-fan-card.active'),visibleCards}
      })
      await page.screenshot({ path: `qa/selection-${width}x${height}.png`, fullPage: true })
      console.log(width+'x'+height,JSON.stringify(result))
      if (result.stage.height > height+1 || result.stage.y < 0 || result.hint.y+result.hint.height > height) throw Error('Selection overflows viewport')
      if (result.heading.y < result.header.y || result.subtitle.y+result.subtitle.height > result.header.y+result.header.height) throw Error('Header text overflows its backdrop')
      if (Math.abs(result.card.x+result.card.width/2-width/2)>10) throw Error('Fan did not center at the initial card')
      if (result.visibleCards > 13) throw Error('Too many card backs are visible at once: '+result.visibleCards)
      if (result.card.width/result.stage.width < .17 || result.card.width/result.stage.width > .19) throw Error('Center card width differs from the approved visual ratio')
      const previousIndex = Number(await page.locator('.flow-fan-card.active').getAttribute('data-card-index'))
      const fanBox = await page.locator('.flow-select-fan').boundingBox()
      const dragY = fanBox.y + fanBox.height/2
      await page.mouse.move(width*.72,dragY)
      await page.mouse.down()
      await page.mouse.move(width*.27,dragY,{steps:12})
      await page.mouse.up()
      await page.waitForTimeout(700)
      const nextIndex = Number(await page.locator('.flow-fan-card.active').getAttribute('data-card-index'))
      if (nextIndex <= previousIndex) throw Error('Fan did not respond to horizontal scrolling')
      const selectedIndex = nextIndex
      await page.locator('.flow-fan-card.active').click()
      await page.getByText('请选择第 2 张牌').waitFor()
      await page.waitForTimeout(320)
      if (await page.locator('.flow-select-slot-card').count() !== 1) throw Error('Selected card did not fill a slot')
      if (await page.locator(`.flow-fan-card[data-card-index="${selectedIndex}"]`).count() !== 0) throw Error('Selected card left a ghost in the fan')
      const leftCard = await page.locator(`.flow-fan-card[data-card-index="${selectedIndex-1}"]`).boundingBox()
      const rightCard = await page.locator(`.flow-fan-card[data-card-index="${selectedIndex+1}"]`).boundingBox()
      if (!leftCard || !rightCard || rightCard.x-leftCard.x-leftCard.width < width*.08) throw Error('Selected card did not leave a visible gap')
      if (width === 440) await page.screenshot({ path:'qa/selection-chosen-440x956.png', fullPage:true })
      await page.close()
    }
    for (const theme of ['事业','财富']) {
      const page = await browser.newPage({ viewport: { width:440, height:956 }, deviceScaleFactor:1 })
      await page.goto('http://127.0.0.1:5173/#/subpages/tarot/index?theme=' + encodeURIComponent(theme))
      await page.evaluate(() => localStorage.clear())
      await page.reload()
      await page.locator('.flow-intro-button').click()
      await page.locator('.flow-select-stage').waitFor()
      await page.waitForTimeout(500)
      const background = await page.locator('.flow-select-stage').evaluate(element => getComputedStyle(element).backgroundImage)
      if (!background.includes(`${theme==='事业'?'career':'wealth'}-selection-scene.webp`)) throw Error(theme+' background is missing')
      const header = await page.locator('.flow-select-header-panel').innerText()
      if (header.includes('♥') || !header.includes('✦')) throw Error(theme+' header still uses love-themed hearts')
      await page.screenshot({ path:`qa/selection-${theme}.png`, fullPage:true })
      await page.close()
    }
    const touchPage = await browser.newPage({ viewport: { width:440,height:956 }, deviceScaleFactor:1, isMobile:true, hasTouch:true })
    await touchPage.goto('http://127.0.0.1:5173/#/subpages/tarot/index?theme=' + encodeURIComponent('爱情'))
    await touchPage.evaluate(() => localStorage.clear())
    await touchPage.reload()
    await touchPage.locator('.flow-intro-button').click()
    const touchBefore = Number(await touchPage.locator('.flow-fan-card.active').getAttribute('data-card-index'))
    const touchFan = await touchPage.locator('.flow-select-fan').boundingBox()
    const cdp = await touchPage.context().newCDPSession(touchPage)
    const y = Math.round(touchFan.y+touchFan.height/2)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:315,y,id:1}]})
    for(let x=300;x>=115;x-=15)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y,id:1}]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await touchPage.waitForTimeout(700)
    const touchAfter = Number(await touchPage.locator('.flow-fan-card.active').getAttribute('data-card-index'))
    if(touchAfter<=touchBefore)throw Error('Touch swipe did not advance the perspective fan')
    await touchPage.close()
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
