const { chromium } = require('C:/Users/aa404/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
    const checkBackdrop = async theme => {
      const src = await page.locator('.flow-post-screen').evaluate(element => getComputedStyle(element).backgroundImage)
      const key = {爱情:'love',事业:'career',财富:'wealth'}[theme]
      if (!src?.includes(`${key}-selection-scene.webp`)) throw new Error(theme + ' post-selection backdrop is wrong: ' + src)
    }
    const checkCareerCardLabels = async () => {
      const clipped = await page.locator('.flow-career .flow-face-meta').evaluateAll(items => items.filter(item => item.scrollWidth > item.clientWidth + 1).map(item => item.textContent))
      if (clipped.length) throw new Error('Career card labels are clipped: ' + clipped.join(', '))
    }
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    for (const [theme, option] of [['爱情', '目前单身'], ['事业', '正在工作'], ['财富', '日常收支']]) {
      await page.goto('http://127.0.0.1:5173/#/subpages/tarot/index?theme=' + encodeURIComponent(theme))
      await page.evaluate(() => localStorage.clear())
      await page.reload()
      await page.locator('.flow-intro-button').waitFor()
      const images = await page.locator('img').evaluateAll(items => items.map(item => ({ src: item.src, loaded: item.complete && item.naturalWidth > 0 })))
      if (images.some(item => !item.loaded)) throw new Error(theme + ' entry image missing: ' + JSON.stringify(images))
      if (theme === '爱情') await page.screenshot({ path: 'qa/tarot-entry.png', fullPage: true })
      const question = page.locator('.flow-intro-input input')
      if (await page.locator('.flow-intro-input').evaluate(element => getComputedStyle(element).backgroundColor) !== 'rgba(0, 0, 0, 0)') throw new Error(theme + ' question input is not transparent')
      await question.fill('想聊一件事')
      if (await question.inputValue() !== '想聊一件事') throw new Error(theme + ' question input failed')
      if (theme === '财富') await page.screenshot({ path: 'qa/tarot-entry-input.png', fullPage: true })
      await page.locator('.flow-intro-button').click()
      const visibleCards = await page.locator('.flow-fan-card').count()
      if (visibleCards < 10 || visibleCards > 16) throw new Error('Visible fan window is out of range: ' + visibleCards)
      if (theme === '爱情') await page.screenshot({ path: 'qa/tarot-selection.png', fullPage: true })
      for (const index of [39, 41, 43]) await page.locator(`.flow-fan-card[data-card-index="${index}"]`).dispatchEvent('click')
      await checkBackdrop(theme)
      if (theme === '事业') await checkCareerCardLabels()
      await page.screenshot({ path: 'qa/tarot-' + theme + '-loading.png', fullPage: true })
      await page.locator('.flow-choice').filter({ hasText: option }).waitFor({ timeout: 5000 })
      await checkBackdrop(theme)
      await page.screenshot({ path: 'qa/tarot-' + theme + '-context.png', fullPage: true })
      await page.locator('.flow-choice').filter({ hasText: option }).click()
      await page.getByText('今天的一小步').waitFor()
      await checkBackdrop(theme)
      if (theme === '事业') await checkCareerCardLabels()
      await page.screenshot({ path: 'qa/tarot-' + theme + '-reading.png', fullPage: true })
      await page.locator('.flow-chip').first().click()
      await page.locator('.flow-follow-copy').waitFor()
      await checkBackdrop(theme)
      if (theme === '爱情') await page.screenshot({ path: 'qa/tarot-followup.png', fullPage: true })
      await page.reload()
      await page.locator('.flow-follow-copy').waitFor()
      console.log(theme + ': flow, images, follow-up, resume passed')
    }
    await page.setViewportSize({ width: 440, height: 956 })
    await page.goto('http://127.0.0.1:5173/#/subpages/tarot/index?theme=' + encodeURIComponent('爱情'))
    await page.evaluate(() => localStorage.clear())
    await page.reload()
    await page.locator('.flow-intro-button').waitFor()
    const layout = await page.evaluate(() => {
      const stage = document.querySelector('.flow-intro-stage').getBoundingClientRect()
      const cards = document.querySelector('.flow-intro-cards').getBoundingClientRect()
      const question = document.querySelector('.flow-intro-question').getBoundingClientRect()
      const backdrop = document.querySelector('.flow-intro-stage')
      return { left: stage.left, right: stage.right, viewport: innerWidth, cardsLeft: cards.left, cardsRight: cards.right, questionLeft: question.left, questionRight: question.right, backdropImage: getComputedStyle(backdrop).backgroundImage }
    })
    if (layout.left < -1 || layout.right > layout.viewport + 1 || layout.cardsLeft <= layout.left || layout.cardsRight >= layout.right || layout.questionLeft <= layout.left || layout.questionRight >= layout.right) throw new Error('Entry controls are cropped on a tall phone: ' + JSON.stringify(layout))
    if (!layout.backdropImage.includes('-selection-scene.webp')) throw new Error('Tall phone backdrop artwork is missing')
    await page.screenshot({ path: 'qa/tarot-iphone16promax.png', fullPage: true })
    if (errors.length) throw new Error('Browser errors: ' + errors.join('; '))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
